Base.@constprop :aggressive function Model{Threaded}(
    f,
    args::NamedTuple,
    defaults::NamedTuple;
    args_on_lhs::Union{Tuple{Vararg{Symbol}},Vector{Symbol},ModelBindingMetadata}=(),
) where {Threaded}
    args_on_lhs = args_on_lhs isa ModelBindingMetadata ? args_on_lhs : Tuple(args_on_lhs)
