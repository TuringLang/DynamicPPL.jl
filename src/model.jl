"""
    Model{Threaded}(f, args::NamedTuple, defaults::NamedTuple; args_on_lhs=())

Store a model function, its arguments, prefix and bindings. Prefer [`@model`](@ref) for
construction. Pass the evaluation context to [`evaluate!!`](@ref).

Set `args_on_lhs` to the names of arguments that occur on the left-hand side of `~`, for
example `Model{false}(f, (; y=1.0), (;); args_on_lhs=(:y,))`. As with `@model`, these
arguments supply observations, which [`condition`](@ref), [`fix`](@ref) and
[`decondition`](@ref) can replace or remove. Without `args_on_lhs`, arguments supply no
observations and cannot be bound. A whole `missing` or `nothing` argument, or a `missing`
element of a supported argument array, supplies no observation; see [Missing data](@ref).

A handwritten evaluator takes `(model, context::Context, varinfo::AbstractVarInfo, args...;
kwargs...)` and must reproduce the argument preparation and binding lookup that `@model`
generates. Calling `tilde_observe!!` directly performs no binding lookup, and the
constructor does not check the evaluator. The steps rely on internal helpers
(`prepare_model_argument`, `_argument_role`, `_check_no_placeholder`), so prefer an
evaluator generated by `@model`. See [Binding rules](@ref).

!!! note "Why keep `Model.f`?"
    Local models can capture variables from the enclosing function:

    ```julia
    function run_analysis(offset)
        @model function demo()
            x ~ Normal(offset, 1)
            return x
        end
        return demo()
    end
    ```

    `run_analysis(1)` and `run_analysis(2)` have the same evaluator type `F` but capture different
    offsets. The field `f` holds these values; the type alone cannot.

    Defining `(model::Model)(...)` or extending a global `get_evaluator` inside `run_analysis`
    requires a global method definition, which Julia rejects there. Using `eval` installs
    the method, but world age prevents the running `run_analysis` from calling it directly.
    We'd need a bridge such as `invokelatest` and separate storage for captures. Keeping `f`
    avoids both.
"""
struct Model{
    F,
    argnames,
    defaultnames,
    Targs,
    Tdefaults,
    Prefix<:Union{VarName,Nothing,PrefixTemplate},
    Values<:BindingTable,
    Threaded,
    ArgsOnLHS,
    OR<:Tuple,
    FR<:Tuple,
} <: AbstractProbabilisticProgram
    f::F
    args::NamedTuple{argnames,Targs}
    defaults::NamedTuple{defaultnames,Tdefaults}
    prefix::Prefix
    values::Values
    observation_removals::OR
    fixed_removals::FR
    # Fields are trusted: validation belongs to the outer constructors.
    function DynamicPPL._new_model(
        f::F,
        args::NamedTuple{A,Ta},
        defaults::NamedTuple{D,Td},
        prefix::P,
        values::V,
        ::Val{Threaded},
        metadata,
        observation_removals::OR,
        fixed_removals::FR,
    ) where {F,A,Ta,D,Td,P,V,Threaded,OR,FR}
        return new{F,A,D,Ta,Td,P,V,Threaded,metadata,OR,FR}(
            f, args, defaults, prefix, values, observation_removals, fixed_removals
        )
    end
end

Base.@constprop :aggressive function Model{Threaded}(
    f,
    args::NamedTuple,
    defaults::NamedTuple,
    prefix::Union{Nothing,VarName,PrefixTemplate},
    values::BindingTable;
    observation_removals=(),
    fixed_removals=(),
    args_on_lhs::Union{Tuple{Vararg{Symbol}},Vector{Symbol},ModelBindingMetadata}=(),
) where {Threaded}
    argument_names = _lhs_arguments(args_on_lhs)
    metadata = args_on_lhs isa ModelBindingMetadata ? args_on_lhs : argument_names
    for name in argument_names
        name in (_argument_names(args)..., _argument_names(defaults)...) || throw(
            ArgumentError("`$name` in `args_on_lhs` is not an argument or default name")
        )
    end
    return _new_model(
        f,
        args,
        defaults,
        prefix,
        values,
        Val(Threaded),
        metadata,
        observation_removals,
        fixed_removals,
    )
end

function _equality_fields(model::Model)
    return (
        model.f,
        model.args,
        model.defaults,
        model.prefix,
        model.values,
        map(keys(merge(model.args, model.defaults))) do n
