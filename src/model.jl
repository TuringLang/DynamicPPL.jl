# One removal per argument: whole placeholders as a tuple, which keeps the model type
# inferable, and array elements as a vector, since splatting it would compile per count.
_unbind_placeholders(model, ::Tuple{}) = model
function _unbind_placeholders(model, found::Tuple)
    names = first(found)
    model = isempty(names) ? model : _unbind(model, names, ConditionRole)
    return _unbind_placeholders(model, Base.tail(found))
end

# Whole `missing`/`nothing` arguments and top-level `missing` array entries supply no
# observation. Scan only arrays whose element type admits `Missing`.
@generated function _placeholder_addresses(
    arguments::NamedTuple{names}, ::Val{args_on_lhs}
) where {names,args_on_lhs}
    found = map(names) do stored_name
        name = unsplat_symbol(stored_name)
        name in args_on_lhs || return :(())
        return :(_placeholder_addresses($(VarName{name}()), arguments.$stored_name))
    end
    return :(($(found...),))
end
_placeholder_addresses(vn::VarName, ::Union{Missing,Nothing}) = ()
_placeholder_addresses(::VarName, value) = ()
function _placeholder_addresses(vn::VarName, value::AbstractArray)
    Missing <: eltype(value) || return ()
    names = [
        AbstractPPL.append_optic(vn, AbstractPPL.Index(Tuple(I), (;))) for
        I in CartesianIndices(value) if isassigned(value, I) && value[I] === missing
    ]
    isempty(names) ||
        _binding_optic(value) === AbstractPPL.Index ||
        throw(
            ArgumentError(
                "Argument `$vn` has `missing` elements, which require supported indexed " *
                "storage; got $(typeof(value)).",
            ),
        )
    return names
end

