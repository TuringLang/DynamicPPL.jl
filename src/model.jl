function _check_no_placeholder(value, vn, ::Union{ConditionRole,FixRole})
    placeholder = _find_placeholder(value)
    absent = placeholder === :missing ? "missing" : "nothing"
    placeholder === :none || throw(
        ArgumentError(
            "LHS variable `$vn` contains `$absent`. Only a whole `missing`/`nothing` " *
            "argument or a `missing` element `x[i]`/`x[i, j]` of a top-level array " *
            "argument marks data unobserved; otherwise use " *
            "`decondition(model, @varname($vn))`, or decondition the enclosing value " *
            "if it is a tuple or struct.",
        ),
    )
    return value
end

function _check_fixed_tilde_size(value::AbstractArray, dist::Distribution, vn)
    expected = size(dist)
    isempty(expected) ||
        size(value) == expected ||
        throw(
            ArgumentError(
                "Fixed value at `$vn` has size $(size(value)), but the distribution has sample size $expected.",
            ),
        )
    return value
end
